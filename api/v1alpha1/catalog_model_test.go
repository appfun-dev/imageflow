func loadCRD(t *testing.T, plural string) *apiextensionsv1.CustomResourceDefinition {
	t.Helper()
	path := filepath.Join("..", "..", "config", "crd", "bases",
		"imageflow.appfun.dev_"+plural+".yaml")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read CRD manifest %s: %v", path, err)
	}
	var crd apiextensionsv1.CustomResourceDefinition
	if err := yaml.Unmarshal(data, &crd); err != nil {
		t.Fatalf("parse CRD manifest %s: %v", path, err)
	}
	return &crd
}

func schemaOf(t *testing.T, crd *apiextensionsv1.CustomResourceDefinition) *apiextensionsv1.JSONSchemaProps {
	t.Helper()
	if len(crd.Spec.Versions) != 1 {
		t.Fatalf("expected exactly one version, got %d", len(crd.Spec.Versions))
	}
	v := crd.Spec.Versions[0]
	if v.Schema == nil || v.Schema.OpenAPIV3Schema == nil {
		t.Fatalf("version %s has no structural schema", v.Name)
	}
	return v.Schema.OpenAPIV3Schema
}

func prop(t *testing.T, s *apiextensionsv1.JSONSchemaProps, path ...string) *apiextensionsv1.JSONSchemaProps {
	t.Helper()
	cur := s
	for _, p := range path {
		next, ok := cur.Properties[p]
		if !ok {
			t.Fatalf("property %q not found under path %v (have: %v)", p, path, keysOf(cur))
		}
		cp := next
		cur = &cp
	}
	return cur
}

func keysOf(s *apiextensionsv1.JSONSchemaProps) []string {
	out := make([]string, 0, len(s.Properties))
	for k := range s.Properties {
		out = append(out, k)
	}
	return out
}

func hasRule(s *apiextensionsv1.JSONSchemaProps, rule string) bool {
	for _, r := range s.XValidations {
		if r.Rule == rule {
			return true
		}
	}
	return false
}

func TestSchemeRegistersAllSevenKinds(t *testing.T) {
	s := runtime.NewScheme()
	if err := AddToScheme(s); err != nil {
		t.Fatalf("AddToScheme: %v", err)
	}
	if GroupVersion.Group != "imageflow.appfun.dev" || GroupVersion.Version != "v1alpha1" {
		t.Fatalf("unexpected GroupVersion %v", GroupVersion)
	}
	kinds := []runtime.Object{
		&ImageStream{}, &ImageStreamList{},
		&ImageArtifact{}, &ImageArtifactList{},
		&ImageSubscription{}, &ImageSubscriptionList{},
		&ImageStreamTag{}, &ImageStreamTagList{},
		&ImageTag{}, &ImageTagList{},
		&ImageStreamImport{}, &ImageStreamImportList{},
		&ImageStreamMapping{}, &ImageStreamMappingList{},
	}
	for _, obj := range kinds {
		gvks, _, err := s.ObjectKinds(obj)
		if err != nil {
			t.Fatalf("scheme does not recognize %T: %v", obj, err)
		}
		if gvks[0].GroupVersion() != GroupVersion {
			t.Fatalf("%T registered under %v, want %v", obj, gvks[0].GroupVersion(), GroupVersion)
		}
	}
}

func TestCRDInventory(t *testing.T) {
	for _, plural := range crdNames {
		crd := loadCRD(t, plural)
		wantName := plural + ".imageflow.appfun.dev"
		if crd.Name != wantName {
			t.Errorf("%s: metadata.name = %q, want %q", plural, crd.Name, wantName)
		}
		if crd.Spec.Group != "imageflow.appfun.dev" {
			t.Errorf("%s: group = %q", plural, crd.Spec.Group)
		}
		wantScope := apiextensionsv1.NamespaceScoped
		if plural == "imageartifacts" {
			wantScope = apiextensionsv1.ClusterScoped
		}
		if crd.Spec.Scope != wantScope {
			t.Errorf("%s: scope = %q, want %q", plural, crd.Spec.Scope, wantScope)
		}
		v := crd.Spec.Versions[0]
		if v.Name != "v1alpha1" || !v.Served || !v.Storage {
			t.Errorf("%s: version = %+v, want single served+storage v1alpha1", plural, v.Name)
		}
		if v.Subresources == nil || v.Subresources.Status == nil {
			t.Errorf("%s: status subresource must be enabled (controller-owned status)", plural)
		}
	}
}

func TestStatusBoundsMatchADR008(t *testing.T) {
	// ImageStream.status.tags[].items — per-tag history depth 3.
	stream := schemaOf(t, loadCRD(t, "imagestreams"))
	items := prop(t, stream, "status", "tags")
	if items.Items == nil || items.Items.Schema == nil {
		t.Fatalf("status.tags has no item schema")
	}
	got := prop(t, items.Items.Schema, "items").MaxItems
	if got == nil || *got != StreamTagHistoryMaxItems {
		t.Errorf("stream history maxItems = %v, want %d", got, StreamTagHistoryMaxItems)
	}

	// ImageSubscription.status.recentDeliveries — recent deliveries 5.
	sub := schemaOf(t, loadCRD(t, "imagesubscriptions"))
	got = prop(t, sub, "status", "recentDeliveries").MaxItems
	if got == nil || *got != SubscriptionDeliveryMaxItems {
		t.Errorf("recentDeliveries maxItems = %v, want %d", got, SubscriptionDeliveryMaxItems)
	}

	// Mirror status events 5 on both mirror kinds; consumers structural cap.
	for _, plural := range []string{"imagestreamtags", "imagetags"} {
		mirror := schemaOf(t, loadCRD(t, plural))
		got = prop(t, mirror, "status", "events").MaxItems
		if got == nil || *got != MirrorEventMaxItems {
			t.Errorf("%s events maxItems = %v, want %d", plural, got, MirrorEventMaxItems)
		}
		got = prop(t, mirror, "status", "consumers").MaxItems
		if got == nil || *got != MirrorConsumerMaxItems {
			t.Errorf("%s consumers maxItems = %v, want %d", plural, got, MirrorConsumerMaxItems)
		}
	}
}

func TestControllerOwnedCELProtection(t *testing.T) {
	const immutable = "self == oldSelf"
	protected := []string{"imageartifacts", "imagestreamtags", "imagetags"}
	for _, plural := range protected {
		spec := prop(t, schemaOf(t, loadCRD(t, plural)), "spec")
		if !hasRule(spec, immutable) {
			t.Errorf("%s: spec must carry the CEL transition rule %q (write protection "+
				"without webhook availability)", plural, immutable)
		}
	}
	// The user-writable kinds must NOT freeze their spec.
	for _, plural := range []string{
		"imagestreams", "imagesubscriptions", "imagestreamimports", "imagestreammappings",
	} {
		spec := prop(t, schemaOf(t, loadCRD(t, plural)), "spec")
		if hasRule(spec, immutable) {
			t.Errorf("%s: spec must stay user-writable, found immutability rule", plural)
		}
	}
}

func TestSubscriptionSpecShape(t *testing.T) {
	sub := schemaOf(t, loadCRD(t, "imagesubscriptions"))
	spec := prop(t, sub, "spec")

	// SourceRef: v1 kind is exactly ImageStreamTag; all three fields required.
	source := prop(t, spec, "source")
	if len(source.Required) != 3 {
		t.Errorf("source required = %v, want [kind name namespace]", source.Required)
	}
	enum := prop(t, source, "kind").Enum
	if len(enum) != 1 || string(enum[0].Raw) != `"ImageStreamTag"` {
		t.Errorf("source.kind enum = %v, want only ImageStreamTag", enum)
	}

	// targets[]: at least one, locator fields both optional (mutual exclusion is
	// webhook-owned per spec decision 6 — no CEL XOR at CRD level).
	targets := prop(t, spec, "targets")
	if targets.MinItems == nil || *targets.MinItems != 1 {
		t.Errorf("targets minItems = %v, want 1", targets.MinItems)
	}
	target := targets.Items.Schema
	for _, f := range []string{"containerNames", "imageFields", "statusPolicyRef"} {
		for _, r := range target.Required {
			if r == f {
				t.Errorf("targets[].%s must be optional (webhook enforces mutual exclusion)", f)
			}
		}
	}
	if hasRule(target, "!(has(self.containerNames) && has(self.imageFields))") ||
		len(target.XValidations) != 0 {
		t.Errorf("targets[] must not carry CEL rules in T2; webhook (T3) owns locator validation")
	}

	// Frozen per-target status vocabulary (ADR-005 §3 + ADR-008 terminals).
	rollout := prop(t, sub, "status", "targets").Items.Schema.Properties["rolloutStatus"]
	want := []string{`"Progressing"`, `"Succeeded"`, `"Failed"`, `"Unknown"`, `"Superseded"`, `"Conflict"`}
	assertEnum(t, "status.targets[].rolloutStatus", rollout.Enum, want)
	health := prop(t, sub, "status", "targets").Items.Schema.Properties["healthStatus"]
	assertEnum(t, "status.targets[].healthStatus", health.Enum,
		[]string{`"Healthy"`, `"Unhealthy"`, `"Unknown"`})
}

func assertEnum(t *testing.T, field string, got []apiextensionsv1.JSON, want []string) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("%s enum has %d entries, want %d", field, len(got), len(want))
	}
	for i := range want {
		if string(got[i].Raw) != want[i] {
			t.Errorf("%s enum[%d] = %s, want %s", field, i, got[i].Raw, want[i])
		}
	}
}

func TestStreamImportPolicyShape(t *testing.T) {
	stream := schemaOf(t, loadCRD(t, "imagestreams"))
	tag := prop(t, stream, "spec", "tags").Items.Schema

	// scheduled ⇒ from (CEL): a scheduled import needs a persistent source to poll.
	found := false
	for _, r := range tag.XValidations {
		if r.Rule == "!has(self.importPolicy) || !self.importPolicy.scheduled || has(self.from)" {
			found = true
		}
	}
	if !found {
		t.Errorf("spec.tags[] missing scheduled⇒from CEL rule, have %+v", tag.XValidations)
	}

	policy := prop(t, tag, "importPolicy")
	scheduled := prop(t, policy, "scheduled")
	if scheduled.Default == nil || string(scheduled.Default.Raw) != "false" {
		t.Errorf("importPolicy.scheduled default = %v, want false", scheduled.Default)
	}
	interval := prop(t, policy, "intervalSeconds")
	if interval.Default == nil || string(interval.Default.Raw) != "900" {
		t.Errorf("importPolicy.intervalSeconds default = %v, want 900 (ADR-004)", interval.Default)
	}
	if interval.Minimum == nil || *interval.Minimum != 1 {
		t.Errorf("importPolicy.intervalSeconds minimum = %v, want 1", interval.Minimum)
	}
	from := prop(t, tag, "from")
	assertEnum(t, "spec.tags[].from.kind", prop(t, from, "kind").Enum, []string{`"DockerImage"`})
}

func TestDigestFieldPatterns(t *testing.T) {
	// Stream history entries and mapping requests are digest-anchored.
	stream := schemaOf(t, loadCRD(t, "imagestreams"))
	item := prop(t, stream, "status", "tags").Items.Schema.Properties["items"].Items.Schema
	if got := prop(t, item, "digest").Pattern; got != DigestPattern {
		t.Errorf("stream status digest pattern = %q, want %q", got, DigestPattern)
	}
	if got := prop(t, item, "imageReference").Pattern; got != DigestReferencePattern {
		t.Errorf("stream status imageReference pattern = %q, want %q", got, DigestReferencePattern)
	}

	mapping := schemaOf(t, loadCRD(t, "imagestreammappings"))
	image := prop(t, mapping, "spec", "image")
	if image.Pattern != DigestReferencePattern {
		t.Errorf("mapping spec.image pattern = %q, want %q (digest references only, ADR-004/005)",
			image.Pattern, DigestReferencePattern)
	}
	required := false
	for _, r := range prop(t, mapping, "spec").Required {
		if r == "image" {
			required = true
		}
	}
	if !required {
		t.Errorf("mapping spec.image must be required")
	}

	artifact := schemaOf(t, loadCRD(t, "imageartifacts"))
	if got := prop(t, artifact, "spec", "digest").Pattern; got != DigestPattern {
		t.Errorf("artifact spec.digest pattern = %q, want %q", got, DigestPattern)
	}
}

func TestDeepCopyIsolation(t *testing.T) {
	original := &ImageSubscription{}
	original.Name = "sub"
	original.Spec.Source = SubscriptionSourceRef{
		Kind: "ImageStreamTag", Name: "payments-api:stable", Namespace: "imageflow-system",
	}
	original.Spec.Targets = []SubscriptionTarget{{
		TargetRef: TargetReference{
			APIVersion: "apps/v1", Kind: "Deployment", Namespace: "app-team", Name: "payments-api",
		},
		ContainerNames: []string{"payments-api"},
	}}
	original.Status.RecentDeliveries = []DeliveryResult{{NewImage: "quay.io/example/app@sha256:" + hex64('a')}}

	copied := original.DeepCopy()
	mutated := "mutated"
	original.Spec.Targets[0].ContainerNames[0] = mutated
	original.Status.RecentDeliveries[0].NewImage = mutated

	if copied.Spec.Targets[0].ContainerNames[0] != "payments-api" {
		t.Errorf("DeepCopy shares containerNames backing array")
	}
	if copied.Status.RecentDeliveries[0].NewImage == mutated {
		t.Errorf("DeepCopy shares recentDeliveries backing array")
	}
}

// hex64 builds a valid 64-char lowercase hex digest body for tests.
func hex64(c byte) string {
	b := make([]byte, 64)
	for i := range b {
		b[i] = c
	}
	return string(b)
}
